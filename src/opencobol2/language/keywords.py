def is_reserved_word(
    text: str,
) -> bool:
    """Return whether a word matches a known reserved word, case-insensitively."""

    if not isinstance(
        text,
        str,
    ):
        raise TypeError(
            "Reserved word lookup text must be a string."
        )

    return text.upper() in RESERVED_WORDS
